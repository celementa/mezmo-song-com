// Граница нетипизированного JSON.
//
// `/api/public/settings` отдаёт конфиг лендинга целиком, и Go в нём — источник
// истины: он присылает больше полей, чем описано в `PublicSiteConfig`, а состав
// полей меняется без правок фронта. Читать такой объект по ключу без каста нельзя,
// поэтому раньше по файлам была рассыпана сотня `as any`.
//
// `Loose` — единственное место, где этот каст объявлен явно и с объяснением.
// Он говорит «здесь читаем сырой JSON по ключу», а не «типы отключены везде»:
// значения всё равно приходится проверять (`typeof x === 'string'`, `String(x)`,
// хелперы `str()`), просто индексация перестаёт быть ошибкой компиляции.
// eslint-disable-next-line @typescript-eslint/no-explicit-any -- см. комментарий выше
export type Loose = Record<string, any>
